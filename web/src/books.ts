/**
 * Как показать книгу, о которой известен только её адрес.
 *
 * Заголовка у книги нет и он не выдумывается (см. `services/books.py`): взять
 * его неоткуда, а подставить вместо него имя первой главы значило бы назвать
 * книгу именем её двенадцатой главы. Остаётся адрес — и по нему книгу узнают,
 * она же по нему и открывалась.
 *
 * Модуль отдельный от экрана намеренно: функция без React проверяется без
 * React, а экспорт не-компонента из файла с компонентами ломает горячую
 * перезагрузку.
 */

/** Имя книги для показа: слаг из адреса, разделители — в пробелы. */
export function bookName(key: string): string {
  const slug = key.replace(/\/+$/, '').split('/').pop() ?? ''
  return slug ? slug.replace(/[-_]+/g, ' ') : key
}
