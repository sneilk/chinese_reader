/**
 * Как показать книгу, о которой известен только её адрес.
 *
 * Сервис заголовка не выдумывает (см. `services/books.py`): взять его
 * неоткуда, а подставить вместо него имя первой главы значило бы назвать книгу
 * именем её двенадцатой главы. Остаётся адрес — и по нему книгу узнают, она же
 * по нему и открывалась.
 *
 * Написать название руками читатель, однако, вправе — и это следует из того же
 * рассуждения: раз вывести имя неоткуда, единственный, кто его знает, — тот,
 * кто книгу читает. Поэтому имён два, и порядок между ними однозначный:
 * написанное человеком важнее выведенного из адреса.
 *
 * Модуль отдельный от экрана намеренно: функция без React проверяется без
 * React, а экспорт не-компонента из файла с компонентами ломает горячую
 * перезагрузку.
 */

import type { BookWalk } from './api'
import { describeError } from './errors'

/** Имя книги из адреса: слаг из ссылки, разделители — в пробелы. */
export function bookName(key: string): string {
  const slug = key.replace(/\/+$/, '').split('/').pop() ?? ''
  return slug ? slug.replace(/[-_]+/g, ' ') : key
}

/**
 * Как книга называется на экране: название читателя, а иначе адрес.
 *
 * Пустое и состоящее из пробелов название равнозначно его отсутствию: строка
 * из пробелов в списке — это книга, по которой нечего нажать.
 */
export function bookLabel(book: { key: string; title?: string | null }): string {
  const title = (book.title ?? '').trim()
  return title || bookName(book.key)
}

/**
 * Состояние выгрузки книги словами.
 *
 * Выгрузка идёт час, и всё это время единственное, что читатель о ней знает, —
 * эта строка. Поэтому состояний тут шесть, а не два: «идёт» и «готово»
 * различаются очевидно, а вот «оборвалась на отказе», «остановлена по
 * просьбе», «книга кончилась» и «ссылки вперёд не было с самого начала»
 * выглядели бы одинаково — «загружено ноль», — хотя означают разное.
 */
export function describeWalk(walk: BookWalk | null, translate: boolean): string {
  if (walk?.running) {
    const asked = walk.cancelled ? ' Остановлюсь, как только дочитаю эту главу.' : ''
    return (
      `Иду вперёд по ссылкам «следующая глава»: загружено ${walk.loaded}.` +
      (asked || ' Можно уйти читать — работа не прервётся.')
    )
  }
  if (walk?.cancelled) {
    return (
      `Остановлено: загружено ${walk.loaded} гл. Загруженное на месте — ` +
      'продолжить можно этой же кнопкой.'
    )
  }
  if (walk?.stopped_by) {
    const reason = describeError(walk.stopped_by).title.toLowerCase()
    return (
      `Остановилась, загрузив ${walk.loaded} гл.: ${reason}. ` +
      'Причина видна в оглавлении, у последней главы.'
    )
  }
  if (walk && walk.loaded > 0) {
    return `Готово: догружено ${walk.loaded} гл. Дальше идти некуда — книга кончилась.`
  }
  if (walk && walk.limit > 0) {
    return 'Дальше идти некуда: ссылки «следующая глава» на последней странице нет.'
  }
  return translate
    ? 'Главы будут переводиться по мере загрузки — это тратит месячный лимит.'
    : 'Загрузит главы без перевода: текст читается и так, а перевод дозаливается кнопкой.'
}
