/**
 * Пауза опроса — единственная часть хука, проверяемая без браузера.
 *
 * Ошибка здесь тихая в обе стороны: пауза не вырастет — телефон долбит мёртвый
 * сервер раз в полторы секунды и садит батарею; вырастет без потолка —
 * читатель не дождётся, когда перевод доедет.
 *
 * Само поведение опроса (не рвётся о сбой, не стирает открытую главу, не
 * кладёт ответ прошлой главы на текущую) проверяется руками в браузере:
 * DOM-окружения здесь нет намеренно, а мок эффектов проверял бы мок.
 */

import { describe, expect, it } from 'vitest'
import { pollDelay } from './useChapter'

describe('pollDelay', () => {
  it('пока всё хорошо — обычный срок', () => {
    expect(pollDelay(0)).toBe(1500)
  })

  it('растёт, пока не получается', () => {
    expect(pollDelay(1)).toBe(3000)
    expect(pollDelay(2)).toBe(6000)
    expect(pollDelay(3)).toBe(12000)
  })

  it('упирается в потолок, а не уходит в бесконечность', () => {
    expect(pollDelay(10)).toBe(pollDelay(3))
    expect(pollDelay(100)).toBe(12000)
  })

  it('никогда не ноль: опрос в тесном цикле — это не опрос', () => {
    for (const failures of [-1, 0, 1, 5, 50]) {
      expect(pollDelay(failures)).toBeGreaterThanOrEqual(1500)
    }
  })

  it('монотонна: каждая следующая неудача ждёт не меньше', () => {
    const delays = [0, 1, 2, 3, 4, 5].map(pollDelay)
    expect(delays).toEqual([...delays].sort((a, b) => a - b))
  })
})
