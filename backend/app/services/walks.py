"""Учёт идущих обходов книги.

Обход двадцати глав — это полминуты, и следить за ним не нужно: главы просто
появляются в оглавлении. Выгрузка книги целиком — другое дело. У книги-образца
550 глав, между запросами к сайту стоит пауза в две секунды, и всё вместе это
час работы, начатой одним нажатием.

Час без единого признака жизни — худший из возможных интерфейсов: непонятно,
идёт ли работа, сколько осталось и не оборвалась ли она на двенадцатой главе,
получив челлендж. Поэтому у обхода есть состояние, и его можно спросить.

Состояние живёт в памяти процесса, а не в базе, и это осознанно. Обход —
свойство запущенной работы, а не книги: переживать перезапуск ему незачем, ведь
и сама работа его не переживает (`pipeline.recover_interrupted` разбирает то,
что от неё осталось). Хранить в базе то, что заведомо протухнет при следующей
выкладке, значило бы показывать «идёт обход» тому, чей обход давно умер.

Пользователь один и процесс один (RFC §10), поэтому и словаря достаточно.

## Обход обязан останавливаться по просьбе

Часовую работу, начатую одним нажатием, нужно уметь прекратить — иначе
ошибочное нажатие стоит часа запросов к чужому сайту. Отсюда флаг остановки,
который обход смотрит между главами: между, а не внутри, потому что прерывать
главу на середине незачем — она докачается за две секунды и ляжет в базу целой.

**Выкладку этот флаг не спасает, и рассчитывать на него там нельзя.** Uvicorn
при остановке фоновые задачи не убивает, а ждёт — «Waiting for background tasks
to complete», — и ждёт их **до** остановки приложения. Значит `stop_all` из
lifespan зовётся тогда, когда ждать уже нечего, и на время выкладки не влияет.
Ограничивает её `--timeout-graceful-shutdown` в юните: uvicorn ждёт десять
секунд и снимает задачу сам, а недописанную главу приберёт
`pipeline.recover_interrupted` на следующем старте.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import UTC, datetime

log = logging.getLogger(__name__)


@dataclass
class Walk:
    """Обход одной книги: сколько просили, сколько прошли, чем кончилось."""

    book_id: int
    #: Потолок этого запуска — сколько глав максимум пройти вперёд.
    limit: int
    #: Сколько глав загружено с начала обхода.
    loaded: int = 0
    running: bool = True
    #: `error_kind` главы, на которой обход остановился. `None` — дошёл до
    #: конца книги или до потолка, то есть остановился штатно.
    stopped_by: str | None = None
    #: Обход попросили прекратить. Это не отказ: загруженное остаётся на месте,
    #: и продолжить можно с той же кнопки.
    cancelled: bool = False
    started_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    finished_at: datetime | None = None


_WALKS: dict[int, Walk] = {}

#: Сервис останавливается. Флаг общий, а не по книге, потому что и повод
#: общий: ждать чужой работы при выкладке не должен ни один обход, в том числе
#: безымянный «ещё N глав» с экрана главы, у которого записи здесь нет.
_STOPPING = False


def current(book_id: int) -> Walk | None:
    """Что известно об обходе этой книги. `None` — её ещё не обходили."""
    return _WALKS.get(book_id)


def start(book_id: int, limit: int) -> Walk | None:
    """Начать обход. `None` — он по этой книге уже идёт.

    Второй обход той же книги не ускорил бы ничего: загрузчик всё равно ходит
    на сайт по одному запросу за раз. Зато он пошёл бы по той же цепочке и
    удвоил счётчик — картинку, по которой читатель судит о работе.
    """
    running = _WALKS.get(book_id)
    if running is not None and running.running:
        log.info("обход книги %s уже идёт, второй не запускаю", book_id)
        return None

    walk = Walk(book_id=book_id, limit=limit)
    _WALKS[book_id] = walk
    log.info("обход книги %s начат, потолок %s глав", book_id, limit)
    return walk


def note_loaded(book_id: int) -> None:
    """Отметить загруженную главу. Это и есть весь прогресс."""
    walk = _WALKS.get(book_id)
    if walk is not None:
        walk.loaded += 1


def request_stop(book_id: int) -> Walk | None:
    """Попросить обход прекратиться. `None` — прекращать нечего.

    Флаг, а не отмена задачи: обход смотрит его между главами и уходит,
    дописав текущую. Убивать задачу на середине незачем — глава докачается за
    две секунды, а брошенная на полпути осталась бы в `fetching`.
    """
    walk = _WALKS.get(book_id)
    if walk is None or not walk.running:
        return walk
    walk.cancelled = True
    log.info("обход книги %s попросили остановить на %s главах", book_id, walk.loaded)
    return walk


def stop_all() -> int:
    """Попросить все обходы прекратиться. Возвращает, скольких попросили.

    Зовётся при остановке приложения. Времени выкладки это не сокращает —
    uvicorn к тому моменту фоновые задачи уже дождался или снял сам по
    `--timeout-graceful-shutdown` (см. шапку модуля). Смысл в другом: обход,
    переживший смену состояния приложения, не должен продолжать ходить на сайт
    браузером, который сейчас закроют.
    """
    global _STOPPING
    _STOPPING = True

    running = [walk for walk in _WALKS.values() if walk.running]
    for walk in running:
        walk.cancelled = True
    if running:
        log.warning("остановка сервиса: прошу прекратить %s обход(ов)", len(running))
    return len(running)


def shutting_down() -> bool:
    """Сервис останавливается — идти дальше по книге незачем."""
    return _STOPPING


def should_stop(book_id: int) -> bool:
    """Пора ли обходу этой книги закончиться.

    Исчезнувшая запись — тоже «пора»: так выглядит книга, удалённая прямо во
    время выгрузки.
    """
    walk = _WALKS.get(book_id)
    return _STOPPING or walk is None or walk.cancelled


def finish(book_id: int, stopped_by: str | None = None) -> None:
    """Закрыть обход: дошёл до конца, упёрся в потолок, оборвался или отменён."""
    walk = _WALKS.get(book_id)
    if walk is None:
        return
    walk.running = False
    walk.stopped_by = stopped_by
    walk.finished_at = datetime.now(UTC)
    log.info(
        "обход книги %s закончен: загружено %s, остановка — %s",
        book_id,
        walk.loaded,
        stopped_by or ("по просьбе" if walk.cancelled else "конец книги"),
    )


def forget(book_id: int) -> None:
    """Забыть обход. Нужно при удалении книги: иначе он переживёт её саму."""
    _WALKS.pop(book_id, None)


def reset() -> None:
    """Забыть все обходы. Только для тестов: между ними состояние не общее."""
    global _STOPPING
    _STOPPING = False
    _WALKS.clear()
