"""Понятия, общие для нескольких слоёв.

Живут отдельно от моделей: загрузчику незачем знать про SQLAlchemy, а слою
БД — про Playwright. Значения совпадают с тем, что лежит в колонках.
"""

import enum


class Language(enum.StrEnum):
    """Язык оригинала главы.

    Определяет три вещи и только их: чем резать текст на токены (jieba против
    регулярки), какими правилами резать на предложения и с какого языка
    переводить. Всё остальное — офсеты, статусы, панель, личный словарь —
    от языка не зависит и написано один раз.

    Русского здесь нет намеренно: это язык **перевода**, а не оригинала.
    Глава на русском не читается — она уже понятна.
    """

    ZH = "zh"
    EN = "en"


#: Язык перевода. Один на всё приложение: читатель русскоязычный.
TARGET_LANGUAGE = "ru"


class ChapterStatus(enum.StrEnum):
    """Состояния конвейера загрузки, RFC §4.

    Глава читаема начиная с `segmented`: текст и токены уже есть, переводов
    может не быть.
    """

    FETCHING = "fetching"
    SEGMENTED = "segmented"
    TRANSLATING = "translating"
    READY = "ready"
    FAILED = "failed"


class ErrorKind(enum.StrEnum):
    """Причины отказа. Пользователь должен видеть их различимо, RFC §4.

    Молча отданная пустая глава — худший из отказов, потому что выглядит как
    баг ридера, а не как проблема на той стороне.
    """

    CHALLENGE = "challenge"
    NOT_FOUND = "not_found"
    EMPTY_EXTRACT = "empty_extract"
    FETCH_TIMEOUT = "fetch_timeout"
    ADAPTER_ERROR = "adapter_error"
    TRANSLATE_FAILED = "translate_failed"
    # Работу оборвал перезапуск сервиса, а не сайт и не провайдер. Своя
    # причина нужна затем, что чинится это ровно повтором и ничем больше —
    # и потому что списывать перезапуск на чужой отказ значит потом искать
    # поломку не там.
    INTERRUPTED = "interrupted"
    # Синтез речи. Отдельно от перевода: перевод есть, читать можно, не
    # получилось только послушать — и чинится это иначе (другая роль, другой
    # тариф, другой сервис).
    SPEECH_FAILED = "speech_failed"
    # Отдельно от translate_failed: это не сбой провайдера, а наш потолок
    # расходов. Чинится не повтором, а решением потратить больше.
    BUDGET_EXCEEDED = "budget_exceeded"
