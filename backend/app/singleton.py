"""Сервис рассчитан ровно на один процесс, и это надо было чем-то подпереть.

Инвариант нигде не был записан, а держится на нём многое:

* **браузер один и профиль у него один.** Chromium не открывает один
  персистентный профиль дважды — второй процесс либо не стартует, либо
  испортит куки, за которые заплачено проходом челленджа (T0.3);
* **реестр обходов живёт в памяти процесса** (`services/walks.py`). У второго
  он свой, и «остановить выгрузку» останавливает не ту;
* **SQLite — один писатель.** Два процесса, пишущие в WAL одновременно, дают
  `database is locked` там, где сейчас его быть не может.

Ничего из этого не ломается заметно. Добавив `--workers 2` в юнит, вы
получите не отказ, а странности: то куки пропали, то кнопка «Остановить» не
работает. Найти причину по симптомам почти невозможно, поэтому она называется
прямо здесь и при старте.

Падать при этом нельзя. Чтение уже загруженных глав второму процессу не
мешает, и уронить сервис целиком из-за неверного флага в юните — хуже, чем
работать вполсилы и громко об этом сказать.
"""

from __future__ import annotations

import fcntl
import logging
import os
from pathlib import Path

log = logging.getLogger(__name__)

#: Держится открытым всё время жизни процесса: закрытие снимает блокировку.
_HANDLE = None
#: Какой именно замок мы держим. В бою каталог данных один, но функция обязана
#: быть определена для любого аргумента, а не только для того, что был первым.
_HELD: Path | None = None


def claim(data_dir: Path) -> bool:
    """Занять место единственного процесса. `False` — место уже занято.

    Блокировка снимается операционной системой сама, когда процесс кончается,
    — в том числе если его убили сигналом. Поэтому файл-замок не нужно
    прибирать и он не может «остаться от прошлого раза».
    """
    global _HANDLE, _HELD

    lock = (data_dir / ".singleton.lock").resolve()

    # Место уже наше. Повторный вопрос — это не второй сервис, а второй запуск
    # lifespan в том же процессе; так живут тесты. Открыв новый дескриптор, мы
    # получили бы отказ от собственной же блокировки: flock считает не процесс,
    # а открытый файл.
    if _HANDLE is not None:
        if lock == _HELD:
            return True
        # Спросили про другой каталог — прежний замок больше не наш.
        _HANDLE.close()
        _HANDLE = None
        _HELD = None
    try:
        data_dir.mkdir(parents=True, exist_ok=True)
        handle = lock.open("w")
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        log.error(
            "сервис уже запущен в другом процессе (%s). Второй процесс сломает "
            "профиль браузера, разделит реестр обходов и начнёт спорить за "
            "запись в базу. Уберите --workers из юнита: приложение рассчитано "
            "на один процесс",
            lock,
        )
        return False
    except OSError as e:
        # Файловая система без flock — не повод не запускаться.
        log.warning("проверка единственности пропущена: %s", e)
        return True

    handle.write(f"{os.getpid()}\n")
    handle.flush()
    _HANDLE = handle
    _HELD = lock
    return True
