"""Приведение текста главы к канону.

Канон — это то, по чему считаются офсеты токенов и границ предложений
([segmentation.md](../../../docs/segmentation.md) §1). Абзац равен строке,
поэтому перевод строки — всегда граница абзаца и никогда не встречается
внутри него.

Одно уточнение к RFC §5.1. Там сказано «привести кавычки к одному виду»;
делать этого мы не стали. Переписывание пунктуации — изменение чужого текста,
которое читатель увидит в ридере, а цель у правила была служебная: чтобы
резчик предложений не спотыкался о разные кодовые точки визуально одинаковых
кавычек. Это достигается тем, что резчик знает **набор** закрывающих кавычек
(см. sentences.py), и текст при этом остаётся нетронутым.
"""

import re
import unicodedata
from collections.abc import Iterable

# Невидимые: соединители нулевой ширины и BOM. Ломают и офсеты, и поиск в словаре.
_ZERO_WIDTH = dict.fromkeys(map(ord, "​‌‍⁠﻿"))

# Экзотические пробелы приводим к обычному. Идеографический U+3000 сюда не
# входит: им набирают красную строку, и его судьба решается отдельно.
_SPACES = str.maketrans(dict.fromkeys("       "
                                      "       ", " "))

_MULTISPACE = re.compile(r"[ \t]+")


def normalize_paragraph(text: str) -> str:
    """Нормализовать один абзац. Возвращает пустую строку, если он пустой."""
    # NFC, а не NFKC: последний схлопнул бы полноширинную пунктуацию в ASCII,
    # а она несёт границы предложений и нужна в тексте как есть.
    text = unicodedata.normalize("NFC", text)
    text = text.translate(_ZERO_WIDTH).translate(_SPACES)
    # Идеографический пробел внутри строки — разделитель, по краям — отступ.
    text = text.replace("　", " ")
    text = _MULTISPACE.sub(" ", text)
    return text.strip()


def normalize(paragraphs: Iterable[str]) -> str:
    """Собрать канон главы из абзацев, полученных адаптером."""
    kept = [p for p in map(normalize_paragraph, paragraphs) if p]
    return "\n".join(kept)
